#!/usr/bin/env node
// Collects the licences of every package shipped in the mobile app (production
// dependencies only) and writes:
//   THIRD_PARTY_NOTICES.md                         full licence texts
//   apps/mobile/src/legal/licenses.generated.ts    list shown in the app
// Fails if a package has a licence outside the allow-list, so a copyleft or
// unlicensed dependency can't slip into a product that is sold as source code.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mobile = join(root, 'apps/mobile');

const ALLOWED = new Set([
  'MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'BlueOak-1.0.0',
  'CC0-1.0', 'Unlicense', 'Python-2.0', 'CC-BY-4.0', 'MIT-0', '(MIT OR CC0-1.0)', '(MIT OR Apache-2.0)',
  '(BSD-2-Clause OR MIT OR Apache-2.0)', 'MIT OR Apache-2.0', 'Apache-2.0 OR MIT', 'MIT AND Apache-2.0',
]);

const tree = JSON.parse(execSync('npm ls --omit=dev --all --json --long', { cwd: mobile, maxBuffer: 256 * 1024 * 1024 }).toString());
const seen = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps || {})) {
    if (!info.path || seen.has(`${name}@${info.version}`)) continue;
    seen.set(`${name}@${info.version}`, { name, version: info.version, path: info.path });
    walk(info.dependencies);
  }
})(tree.dependencies);

const packages = [...seen.values()]
  .map((p) => {
    const pkg = JSON.parse(readFileSync(join(p.path, 'package.json'), 'utf8'));
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses || []).map((l) => l.type).join(' OR ') ?? 'UNKNOWN';
    const file = existsSync(p.path) ? readdirSync(p.path).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f)) : undefined;
    const text = file ? readFileSync(join(p.path, file), 'utf8').trim() : '';
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '';
    return { name: p.name, version: p.version, license: license || 'UNKNOWN', repository: repo, text };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const bad = packages.filter((p) => !ALLOWED.has(p.license));
if (bad.length) {
  console.error('Packages with licences that need review:\n' + bad.map((p) => `  ${p.name}@${p.version}: ${p.license}`).join('\n'));
  console.error('\nReview each licence, then add it to ALLOWED in scripts/third-party-notices.mjs if it is compatible.');
  process.exit(1);
}

writeFileSync(
  join(root, 'THIRD_PARTY_NOTICES.md'),
  `# Third-party notices\n\nThe Crewdeck mobile app includes the following open-source packages. Generated by \`npm run notices\`.\n\n` +
    packages
      .map((p) => `## ${p.name} ${p.version}\n\nLicence: ${p.license}${p.repository ? `\nSource: ${p.repository}` : ''}\n\n${p.text ? '```\n' + p.text + '\n```' : '_No licence file shipped in the package; licence declared in package.json._'}\n`)
      .join('\n')
);

writeFileSync(
  join(mobile, 'src/legal/licenses.generated.ts'),
  `// AUTO-GENERATED by scripts/third-party-notices.mjs. Do not edit by hand.\nexport const LICENSES: { name: string; version: string; license: string }[] = ${JSON.stringify(
    packages.map(({ name, version, license }) => ({ name, version, license })),
    null,
    1
  )};\n`
);

const counts = packages.reduce((acc, p) => ((acc[p.license] = (acc[p.license] || 0) + 1), acc), {});
console.log(`${packages.length} packages. Licences:`, counts);
