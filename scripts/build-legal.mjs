#!/usr/bin/env node
// Generates the legal documents and website from a single source:
//   business.config.json + legal/*.md + apps/web/src/*.html
// Outputs:
//   apps/mobile/src/legal/generated.ts  (in-app policies + business details)
//   apps/web/public/*.html              (website pages)
// Run with: npm run build:legal
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseBlocks, blocksToHtml, parseFrontmatter, fillTemplate } from './lib/markdown.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(readFileSync(join(root, 'business.config.json'), 'utf8'));
delete config.$comment;
config.copyrightYear = config.effectiveDate.slice(0, 4);

// ---- Legal documents ------------------------------------------------------
const legalDir = join(root, 'legal');
const docs = readdirSync(legalDir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((file) => {
    const { meta, body } = parseFrontmatter(readFileSync(join(legalDir, file), 'utf8'));
    const filled = fillTemplate(body, config);
    // The page title is rendered by the app/website chrome, so drop the H1.
    const blocks = parseBlocks(filled).filter((b, idx) => !(idx === 0 && b.type === 'heading' && b.level === 1));
    return { slug: meta.slug, title: meta.title, blocks };
  });

// ---- Mobile app module ----------------------------------------------------
const mobileOut = join(root, 'apps/mobile/src/legal/generated.ts');
mkdirSync(dirname(mobileOut), { recursive: true });
const docMap = Object.fromEntries(docs.map((d) => [d.slug, { title: d.title, blocks: d.blocks }]));
writeFileSync(
  mobileOut,
  `// AUTO-GENERATED by scripts/build-legal.mjs. Do not edit by hand.
// Edit legal/*.md or business.config.json, then run \`npm run build:legal\`.
import type { LegalDoc } from './types';

export const BUSINESS = ${JSON.stringify(config, null, 2)} as const;

export const LEGAL_DOCS: Record<string, LegalDoc> = ${JSON.stringify(docMap, null, 2)};
`
);

// ---- Website --------------------------------------------------------------
const webSrc = join(root, 'apps/web/src');
const webOut = join(root, 'apps/web/public');
mkdirSync(webOut, { recursive: true });
const layout = readFileSync(join(webSrc, '_layout.html'), 'utf8');

const render = ({ title, description, content }) =>
  fillTemplate(
    layout.replace('{{content}}', () => content),
    { ...config, pageTitle: title, pageDescription: description }
  );

for (const doc of docs) {
  const content = `<article class="prose"><h1>${doc.title}</h1>\n${blocksToHtml(doc.blocks)}</article>`;
  writeFileSync(
    join(webOut, `${doc.slug}.html`),
    render({ title: doc.title, description: `${config.appName} ${doc.title}`, content })
  );
}

for (const file of readdirSync(webSrc)) {
  if (file.startsWith('_')) continue;
  const src = join(webSrc, file);
  if (file.endsWith('.html')) {
    const raw = readFileSync(src, 'utf8');
    const { meta, body } = parseFrontmatter(raw);
    writeFileSync(
      join(webOut, file),
      render({ title: meta.title, description: meta.description, content: fillTemplate(body, config) })
    );
  } else {
    copyFileSync(src, join(webOut, file));
  }
}

const shared = join(root, 'apps/mobile/assets/images/icon.png');
if (existsSync(shared)) copyFileSync(shared, join(webOut, 'icon.png'));

console.log(`Built ${docs.length} legal documents → app + website (${webOut}).`);
